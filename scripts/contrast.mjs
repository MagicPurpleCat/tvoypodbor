// Проверка WCAG-контрастности пар «текст / фон» палитры.
// Запуск: node scripts/contrast.mjs
const lum = (hex) => {
  const [r, g, b] = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

const pairs = [
  ['#FFFFFF', '#07080B', 'заголовки на фоне'],
  ['#FFFFFF', '#1A1C23', 'заголовки на карточке'],
  ['#A0A0A0', '#07080B', 'вторичный текст на фоне'],
  ['#A0A0A0', '#1A1C23', 'вторичный текст на карточке'],
  ['#A0A0A0', '#22252E', 'вторичный текст на светлой части градиента карточки'],
  ['#07080B', '#00FF9D', 'текст CTA (начало градиента)'],
  ['#07080B', '#00D46B', 'текст CTA (конец градиента)'],
  ['#00FF9D', '#1A1C23', 'зелёные суммы на карточке'],
  ['#FFFFFF', '#4A55E2', 'текст вторичной кнопки (начало)'],
  ['#FFFFFF', '#5660F0', 'текст вторичной кнопки (центр градиента)'],
  ['#FFFFFF', '#636CFF', 'текст вторичной кнопки (конец)'],
  ['#8F96FF', '#1A1C23', 'фиолетовый текст статуса на карточке'],
  ['#FF5E5E', '#1A1C23', 'текст ошибки/лимита на карточке'],
  ['#FF5E5E', '#07080B', 'текст ошибки/таймер на фоне'],
  ['#07080B', '#FF5E5E', 'тёмный текст на красной плашке'],
];

for (const [fg, bg, note] of pairs) {
  const r = ratio(fg, bg);
  const mark = r >= 4.5 ? 'OK ' : r >= 3 ? 'L  ' : 'BAD';
  console.log(`${mark} ${r.toFixed(2).padStart(5)}:1  ${fg} на ${bg}  — ${note}`);
}
console.log('\nOK — ≥4.5:1 (обычный текст), L — только крупный текст ≥18.66px bold / 24px, BAD — нельзя.');
